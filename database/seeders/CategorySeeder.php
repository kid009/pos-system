<?php

namespace Database\Seeders;

use App\Models\Category;
use Illuminate\Database\Seeder;
use Illuminate\Support\Str;

class CategorySeeder extends Seeder
{
    public function run(): void
    {
        // 1. นำข้อมูลดิบของพี่กั๊กมาใส่ในรูปแบบ String เพื่อทำการตัดคำซ้ำด้วย PHP หลังบ้าน
        $rawCategories = 'อุปกรณ์เตาแก๊สอุปกรณ์เตาแก๊สอุปกรณ์เตาแก๊สอุปกรณ์เตาแก๊สอุปกรณ์เตาแก๊สอะไหล่เตาแก๊สอะไหล่เตาแก๊สอุปกรณ์เตาแก๊สอุปกรณ์เตาแก๊สอุปกรณ์เตาแก๊สอุปกรณ์เตาแก๊สอะไหล่เตาแก๊สอะไหล่เตาแก๊สอะไหล่เตาแก๊สอุปกรณ์เตาแก๊สอุปกรณ์เตาแก๊สอะไหล่เตาแก๊สอะไหล่เตาแก๊สอะไหล่เตาแก๊สอะไหล่เตาแก๊สอุปกรณ์เตาแก๊สอะไหล่เตาแก๊สอะไหล่เตาแก๊สอะไหล่เตาแก๊สอะไหล่เตาแก๊สอะไหล่เตาแก๊สอะไหล่เตาแก๊สอุปกรณ์เตาแก๊สโครงเตาแก๊สโครงเตาแก๊สโครงเตาแก๊สโครงเตาแก๊สเตาแก๊สเตาแก๊สเตาแก๊สเตาแก๊สเตาแก๊สเตาแก๊สเตาแก๊สเตาแก๊สอุปกรณ์เตาแก๊สเตาแก๊สเตาแก๊สเตาแก๊สเตาแก๊สเตาแก๊สเตาแก๊สเตาแก๊สเตาแก๊สอุปกรณ์เตาแก๊สอุปกรณ์เตาแก๊สอะไหล่เตาแก๊สอุปกรณ์เตาแก๊สโครงเตาแก๊สโครงเตาแก๊สโครงเตาแก๊สอุปกรณ์เตาแก๊สอุปกรณ์เตาแก๊สโครงเตาแก๊สโครงเตาแก๊สโครงเตาแก๊สโครงเตาแก๊สโครงเตาแก๊สโครงเตาแก๊สอุปกรณ์เตาแก๊สอุปกรณ์เตาแก๊สอุปกรณ์เตาแก๊สอุปกรณ์เตาแก๊สอุปกรณ์เตาแก๊สอุปกรณ์เตาแก๊สอุปกรณ์เตาแก๊สอุปกรณ์เตาแก๊สอุปกรณ์เตาแก๊สอุปกรณ์เตาแก๊ส';

        // 2. ใช้ Regular Expression ในการแยกกลุ่มคำภาษาไทยอย่างแม่นยำ[cite: 2]
        // ค้นหาคำหลัก: อุปกรณ์เตาแก๊ส | อะไหล่เตาแก๊ส | โครงเตาแก๊ส | เตาแก๊ส
        preg_match_all('/อุปกรณ์เตาแก๊ส|อะไหล่เตาแก๊ส|โครงเตาแก๊ส|เตาแก๊ส/', $rawCategories, $matches);

        // 3. ทำการ Deduplicate ตัดคำซ้ำออกทั้งหมดด้วย array_unique
        $cleanCategories = array_unique($matches[0]);

        // 4. วนลูปบันทึกข้อมูลเข้าฐานข้อมูลแบบ Idempotent (รันซ้ำได้ปลอดภัย สต็อกไม่เบิ้ล ข้อมูลไม่พัง)
        foreach ($cleanCategories as $categoryName) {

            // สร้าง URL Slug รองรับระบบ E-Commerce หน้าร้าน
            $slug = Str::slug($categoryName);
            if (empty($slug)) {
                // รองรับ Fallback สำหรับอักขระภาษาไทยป้องกัน Slug ว่างเปล่า
                $slug = urlencode($categoryName);
            }

            // ใช้ firstOrCreate เพื่อรับประกันว่าถ้าระบบเคยรัน Seeder ตัวนี้ไปแล้ว จะไม่บันทึกซ้ำซ้อน
            Category::firstOrCreate(
                ['slug' => $slug], // ตรวจสอบเงื่อนไขจากคอลัมน์ที่ไม่ซ้ำกัน (Unique Column)
                [
                    'name' => $categoryName,
                    'is_active' => true,
                    'created_at' => now(),
                    'updated_at' => now(),
                ]
            );
        }
    }
}
